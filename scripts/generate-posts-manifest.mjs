// Reads content/posts/*.mdx and writes their frontmatter into a plain TS module.
//
// This exists because the filesystem cannot be read from inside the worker.
// Marking a route static is not enough: OpenNext still invokes the server
// function for App Router pages, so a readdirSync at request time fails with
//   Error: no such file or directory, readdir '/bundle/content/posts'
//
// Generating a module instead means the post list is bundled as data, and
// gray-matter never ships to the runtime.
//
// Runs as part of `pnpm build` and `pnpm dev`.

import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import matter from "gray-matter"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const POSTS_DIR = join(ROOT, "content/posts")
const OUT = join(ROOT, "src/data/posts.generated.ts")

const posts = readdirSync(POSTS_DIR)
  .filter((f) => /\.mdx?$/.test(f))
  .map((filename) => {
    const slug = filename.replace(/\.mdx?$/, "")
    const { data } = matter(readFileSync(join(POSTS_DIR, filename), "utf8"))

    if (!data.title || !data.date) {
      throw new Error(
        `content/posts/${filename}: frontmatter needs both title and date`,
      )
    }

    return {
      slug,
      title: String(data.title),
      // YAML parses an unquoted date into a Date, so normalise to YYYY-MM-DD.
      date: new Date(data.date).toISOString().slice(0, 10),
      summary: String(data.summary ?? ""),
      tags: Array.isArray(data.tags) ? data.tags.map(String) : [],
      cover: data.cover ? String(data.cover) : null,
      draft: data.draft === true,
    }
  })
  .sort((a, b) => b.date.localeCompare(a.date))

const body = `// GENERATED by scripts/generate-posts-manifest.mjs — do not edit.
// Regenerate with \`pnpm posts:manifest\` (also runs on build and dev).
import type { Post } from "./posts"

const posts: Post[] = ${JSON.stringify(posts, null, 2)}

export default posts
`

writeFileSync(OUT, body)

const live = posts.filter((p) => !p.draft).length
console.log(
  `posts manifest: ${posts.length} file(s), ${live} published, ${posts.length - live} draft`,
)
